package api

import (
	"context"
	"fmt"

	"github.com/google/uuid"
)

// RebuildEmbeddingsResult tallies what RebuildEmbeddings actually did
// across one call's messageIDs — the rebuild counterpart of
// EmbedMessagesResult, with "Replaced" in place of "Embedded"/
// "AlreadyEmbedded" (a rebuild has no "already done, skip it" case by
// design: every message with text gets re-embedded every time, see
// RebuildEmbeddings' own doc comment on why that's deliberate, not an
// oversight).
type RebuildEmbeddingsResult struct {
	Replaced      int
	SkippedNoText int
	Failed        int
}

// RebuildEmbeddings is the one-time fix for every embeddings row written
// before the nomic-embed-text task-prefix fix (extraction.
// EmbeddingDocumentPrefix/EmbeddingQueryPrefix's own doc comment):
// those rows were generated by the old, prefix-less Embed(), so a
// (correctly) prefixed query vector compared against them can rank
// WORSE than it did before that fix shipped. This recomputes every
// message's document embedding with the new, correct EmbedDocument path
// and atomically swaps it in via EmbeddingStore.ReplaceForMessage.
//
// Deploy order, stated explicitly because getting it backwards defeats
// the whole point: merge the task-prefix fix (EmbedDocument/EmbedQuery
// already wired into embedMessages/SearchSemantic/GetRelevantContext),
// run this once against the real data (cmd/backfill_embeddings
// --rebuild), THEN resume normal operation. Running normal traffic
// against a mix of old (un-prefixed) and new (prefixed) vectors for any
// length of time is exactly the degraded state this method exists to
// close, not a steady state to tolerate.
//
// For every message with embeddable text (messageText's own rule —
// same one embedMessages uses): compute the new document embedding
// FIRST, via EmbedDocument, THEN call ReplaceForMessage. That order is
// load-bearing, not incidental — if EmbedDocument fails, this never
// calls ReplaceForMessage at all, so the message's EXISTING row (old
// vector or not) is left completely untouched; a message is never
// observed with zero embedding rows at any point during this run. Takes
// messageIDs explicitly (not "every message in the table," unscoped) —
// the same reason BackfillEmbeddings does: callers batch and a caller
// controls exactly which messages one call touches, including a test
// scoping itself to its own seeded rows against this suite's shared,
// persistent dev database rather than reprocessing everything else
// already sitting in it.
//
// Deliberately NOT idempotent the way BackfillEmbeddings is (that one
// skips a message that already has a row; this one has no such
// skip-if-present check) — by design: re-embedding a message that
// already has a CORRECT, post-fix vector is a wasted Costguard call but
// not wrong, and a rebuild run needs to re-embed EVERY message with
// text regardless of whether some of them were already touched by an
// earlier, partial, or re-run of this same rebuild. Safe to re-run as
// many times as needed for exactly that reason.
//
// Failure behavior matches embedMessages' own log-and-continue
// philosophy: embedding or storage failure for one message is logged
// via a.logf with the message ID and error, counted as Failed, and the
// run continues — a transient Costguard/DB issue on one message must
// never abort the whole rebuild or leave an EARLIER message's
// already-replaced row in doubt.
//
// Never touches edges or messages — only embeddings rows, via
// ReplaceForMessage. No schema change: embeddings stay immutable rows in
// the general case: replacement here is delete-and-insert in one
// transaction, not an in-place UPDATE.
//
// Same nil-Embedder-is-a-real-misconfiguration reasoning as
// BackfillEmbeddings (its own doc comment): rebuilding embeddings IS the
// entire point of calling this, so a nil Embedder must surface as an
// error, not a silent zero-count no-op.
func (a *API) RebuildEmbeddings(ctx context.Context, messageIDs []uuid.UUID) (RebuildEmbeddingsResult, error) {
	if a.embedder == nil {
		return RebuildEmbeddingsResult{}, fmt.Errorf("RebuildEmbeddings: API has no Embedder configured — construct via New(..., embedder) with a non-nil embedder")
	}

	var result RebuildEmbeddingsResult
	seen := make(map[uuid.UUID]bool, len(messageIDs))
	for _, id := range messageIDs {
		if seen[id] {
			continue
		}
		seen[id] = true

		msg, err := a.messages.GetByID(ctx, id)
		if err != nil {
			a.logf("RebuildEmbeddings: load message %s: %v", id, err)
			result.Failed++
			continue
		}

		text, ok := messageText(msg)
		if !ok {
			result.SkippedNoText++
			continue
		}

		vec, err := a.embedder.EmbedDocument(ctx, text)
		if err != nil {
			a.logf("RebuildEmbeddings: embed message %s: %v", id, err)
			result.Failed++
			continue
		}

		if err := a.embeddings.ReplaceForMessage(ctx, id, vec); err != nil {
			a.logf("RebuildEmbeddings: replace embedding for message %s: %v", id, err)
			result.Failed++
			continue
		}

		result.Replaced++
	}

	return result, nil
}
